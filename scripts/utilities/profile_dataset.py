from pathlib import Path
import pandas as pd

RAW_DIR = Path("data/raw")
REPORT_PATH = Path("docs/profiling_report.md")


def suggest_postgres_type(series):
    dtype = str(series.dtype).lower()
    name = series.name.lower()

    if "timestamp" in name or "date" in name:
        return "TIMESTAMP"

    if "int" in dtype:
        return "INTEGER"

    if "float" in dtype:
        return "NUMERIC(10,2)"

    if "bool" in dtype:
        return "BOOLEAN"

    max_len = series.dropna().astype(str).str.len().max()

    if pd.isna(max_len):
        return "TEXT"

    if max_len <= 2:
        return "CHAR(2)"

    if max_len <= 10:
        return "VARCHAR(10)"

    if max_len <= 20:
        return "VARCHAR(20)"

    if max_len <= 32:
        return "VARCHAR(32)"

    if max_len <= 64:
        return "VARCHAR(64)"

    if max_len <= 128:
        return "VARCHAR(128)"

    if max_len <= 255:
        return "VARCHAR(255)"

    return "TEXT"


def profile_dataset(csv_file):

    df = pd.read_csv(csv_file)

    report = []

    report.append(f"# {csv_file.name}\n")

    report.append("## Dataset Summary\n")

    report.append(f"- Rows: {len(df):,}")
    report.append(f"- Columns: {len(df.columns)}")
    report.append(f"- File Size: {csv_file.stat().st_size/1024/1024:.2f} MB")
    report.append(f"- Memory Usage: {df.memory_usage(deep=True).sum()/1024/1024:.2f} MB")
    report.append(f"- Duplicate Rows: {df.duplicated().sum():,}")

    report.append("\n---\n")

    report.append("## Column Analysis\n")

    report.append("|Column|Pandas|PostgreSQL|NULL|Missing %|Unique|Max Length|Constraint|")
    report.append("|------|------|----------|----|----------|------|----------|----------|")
   
    for col in df.columns:

        missing = df[col].isna().sum()
        missing_pct = missing / len(df) * 100
        unique = df[col].nunique(dropna=True)

        # --- REPLACE YOUR OLD max_len CODE WITH THIS ---
        if df[col].dtype == "object":
            max_len = (
                df[col]
                .dropna()
                .astype(str)
                .str.len()
                .max()
            )

            if pd.isna(max_len):
                max_len = "-"
        else:
            max_len = "-"
        # -----------------------------------------------

        constraint = "NOT NULL" if missing == 0 else "NULL"

        report.append(
            f"|{col}|"
            f"{df[col].dtype}|"
            f"{suggest_postgres_type(df[col])}|"
            f"{missing:,}|"
            f"{missing_pct:.2f}%|"
            f"{unique:,}|"
            f"{max_len}|"
            f"{constraint}|"
        )

    report.append("\n---\n")

    report.append("## Statistics\n")

    numeric = df.select_dtypes(include="number")

    if numeric.empty:

        report.append("No numeric columns.\n")

    else:

        for col in numeric.columns:

            report.append(f"### {col}")

            report.append(f"- Minimum : {numeric[col].min()}")
            report.append(f"- Maximum : {numeric[col].max()}")
            report.append(f"- Mean : {numeric[col].mean():.2f}")

            report.append("")

    report.append("---\n")

    report.append("## Example Values\n")

    for col in df.columns:

        examples = (
            df[col]
            .dropna()
            .astype(str)
            .unique()[:5]
        )

        report.append(f"### {col}")

        for value in examples:
            report.append(f"- {value}")

        report.append("")

    report.append("---\n")

    report.append("## Recommendations\n")

    for col in df.columns:

        unique = df[col].nunique(dropna=True)
        missing = df[col].isna().sum()

        if (
            col.endswith("_id")
            and unique == len(df)
            and missing == 0
        ):
            report.append(
                f"- **{col}** → PRIMARY KEY "
                f"({suggest_postgres_type(df[col])})"
            )

        elif col.endswith("_id"):
            report.append(
                f"- **{col}** → Possible FOREIGN KEY"
            )

        if missing == 0:
            report.append(
                f"- **{col}** → Recommend NOT NULL"
            )

    report.append("\n\n")

    return "\n".join(report)


def main():

    output = []

    output.append("# Olist Data Profiling Report\n")

    output.append(
        "This report was automatically generated by "
        "`scripts/utilities/profile_dataset.py`.\n"
    )

    output.append("---\n")

    for csv in sorted(RAW_DIR.glob("*.csv")):

        output.append(profile_dataset(csv))

    REPORT_PATH.write_text(
        "\n".join(output),
        encoding="utf-8"
    )

    print(f"\nReport saved to:\n{REPORT_PATH.resolve()}")


if __name__ == "__main__":
    main()